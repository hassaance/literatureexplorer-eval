"""Step 3: merge hand-written and kept generated questions into the final test set.

    python 03_build_testset.py                 # hand-written + generated
    python 03_build_testset.py --handwritten-only

Writes testset/testset.jsonl (used by the other scripts) and testset/testset.csv (for reading).
"""

import argparse
import json

import pandas as pd

from evalkit import config

FIELDS = ["id", "question_type", "question", "reference", "expected_behavior", "source_doc_ids",
          "source_titles", "categories", "base_id", "origin", "verification", "reference_context", "note"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--handwritten-only", action="store_true")
    args = ap.parse_args()

    docs = pd.read_csv(config.DOCUMENTS_CSV).set_index("doc_id")
    ver = {}
    vf = config.DATA / "handwritten_validation.csv"
    if vf.exists():
        ver = pd.read_csv(vf).set_index("id")["verdict"].to_dict()

    items = []
    for line in open(config.HANDWRITTEN_JSONL, encoding="utf-8"):
        it = json.loads(line)
        it["source_titles"] = [docs.loc[d, "title"] for d in it["source_doc_ids"]]
        it["categories"] = [docs.loc[d, "category"] for d in it["source_doc_ids"]]
        it["verification"] = ver.get(it["id"], "not_checked" if it.get("needs_verification") else "n/a")
        it["reference_context"] = ""
        items.append(it)

    if not args.handwritten_only:
        if not config.GENERATED_JSONL.exists():
            raise SystemExit("No generated questions yet: run 02_generate_testset.py or use --handwritten-only.")
        n = 0
        for line in open(config.GENERATED_JSONL, encoding="utf-8"):
            c = json.loads(line)
            if not c["keep"]:
                continue
            n += 1
            c["id"] = f"G-{n:03d}"
            c["verification"] = f"generated by {c['generator']}, checked by {c['checker']}"
            c["base_id"], c["note"] = None, ""
            items.append(c)

    with open(config.TESTSET_JSONL, "w", encoding="utf-8") as f:
        for it in items:
            f.write(json.dumps({k: it.get(k) for k in FIELDS}, ensure_ascii=False) + "\n")
    df = pd.DataFrame([{k: it.get(k) for k in FIELDS} for it in items])
    for col in ("source_doc_ids", "source_titles", "categories"):
        df[col] = df[col].map(lambda v: "; ".join(v) if isinstance(v, list) else "")
    df.to_csv(config.TESTSET / "testset.csv", index=False)
    print(df.groupby(["question_type", "expected_behavior"]).size().to_string())
    print(f"\n{len(df)} questions -> {config.TESTSET_JSONL}")
    print(f"endpoint requests needed for 04_query_endpoint.py: {2 * len(df)}")


if __name__ == "__main__":
    main()
